/* =========================================================
   VISIBLE SKILLS
   Automatically updates when skills are added.
========================================================= */

export const visibleSkills =
  skills
    .filter(
      (skill) =>
        skill &&
        skill.show !== false
    )
    .sort(
      (a, b) =>
        (a.order ?? 999) -
        (b.order ?? 999)
    );


/* =========================================================
   FEATURED SKILLS
========================================================= */

export const featuredSkills =
  visibleSkills.filter(
    (skill) =>
      skill.featured === true
  );


/* =========================================================
   CATEGORIES
   Automatically generated.
========================================================= */

export const skillCategories = [
  "All",
  ...new Set(
    visibleSkills.map(
      (skill) =>
        skill.category
    )
  ),
];


/* =========================================================
   GET SKILLS BY CATEGORY
========================================================= */

export function getSkillsByCategory(category) {

  if (
    !category ||
    category.toLowerCase() === "all"
  ) {
    return visibleSkills;
  }

  return visibleSkills.filter(
    (skill) =>
      skill.category.toLowerCase() ===
      category.toLowerCase()
  );
}


/* =========================================================
   GET SKILLS BY TYPE
========================================================= */

export function getSkillsByType(type) {

  if (
    !type ||
    typeof type !== "string"
  ) {
    return [];
  }

  return visibleSkills.filter(
    (skill) =>
      skill.type.toLowerCase() ===
      type.toLowerCase()
  );
}


/* =========================================================
   FIND SKILL BY ID
========================================================= */

export function getSkillById(id) {

  return skills.find(
    (skill) =>
      skill.id === id
  );
}


/* =========================================================
   FIND SKILL BY NAME
========================================================= */

export function getSkillByName(name) {

  if (
    !name ||
    typeof name !== "string"
  ) {
    return undefined;
  }

  return skills.find(
    (skill) =>
      skill.name.toLowerCase() ===
      name.toLowerCase()
  );
}


/* =========================================================
   GET SKILL NAMES
========================================================= */

export function getSkillNames() {

  return visibleSkills.map(
    (skill) =>
      skill.name
  );
}


/* =========================================================
   GET SKILL COUNT
========================================================= */

export function getSkillCount() {

  return visibleSkills.length;
}


/* =========================================================
   GET FEATURED SKILL COUNT
========================================================= */

export function getFeaturedSkillCount() {

  return featuredSkills.length;
}


/* =========================================================
   GET CATEGORY COUNT
========================================================= */

export function getCategoryCount() {

  return skillCategories.length - 1;
}


/* =========================================================
   DEFAULT EXPORT
========================================================= */

export default skills;
